const MAX_PROOF_BYTES: u64 = 8 * 1024 * 1024;

#[derive(Parser)]
#[command(name = "zectime")]
#[command(about = "Private Zcash timestamp receipts with blind ZK commitments")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Generate IPA parameters for timestamp-open proofs.
    Setup(SetupArgs),
    /// Timestamp receipt operations.
    Timestamp(TimestampArgs),
}

#[derive(clap::Args)]
struct SetupArgs {
    /// Output file for serialized IPA parameters.
    #[arg(long)]
    params: PathBuf,
    /// Circuit size parameter.
    #[arg(long, default_value_t = TIMESTAMP_CIRCUIT_K)]
    k: u32,
}

#[derive(clap::Args)]
struct TimestampArgs {
    #[command(subcommand)]
    command: TimestampCommand,
}

#[derive(Subcommand)]
enum TimestampCommand {
    /// Hash a file, create a blind commitment, and write receipt JSON.
    Stamp(TimestampStampArgs),
    /// Build a Halo2 proof that opens a receipt commitment.
    Reveal(TimestampRevealArgs),
    /// Verify a timestamp-open proof.
    Verify(TimestampVerifyArgs),
    /// Publish a receipt commitment in a Zcash Orchard memo via zallet.
    Anchor(TimestampAnchorArgs),
    /// Fetch a confirmed timestamp memo by txid.
    Fetch(TimestampFetchArgs),
    /// Generate IPA parameters for predicate proofs.
    PredicateSetup(TimestampPredicateSetupArgs),
    /// Build a predicate proof from witness JSON.
    PredicateProve(TimestampPredicateProveArgs),
    /// Verify a predicate proof.
    PredicateVerify(TimestampPredicateVerifyArgs),
}

