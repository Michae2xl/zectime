fn run_predicate_prove(args: TimestampPredicateProveArgs) -> Result<()> {
    let witness: PredicateWitness =
        serde_json::from_reader(BufReader::new(File::open(&args.witness)?))?;
    let params = read_params(BufReader::new(File::open(&args.params)?))?;
    let artifacts = TimestampPredicateProvingArtifacts::from_params(params)?;
    let proof = prove_timestamp_predicate(&artifacts, &witness)?;
    let file = create_file(&args.out)?;
    serde_json::to_writer(BufWriter::new(file), &proof)?;
    print_predicate_public_inputs(&proof);
    println!("wrote predicate proof to {}", args.out.display());
    Ok(())
}

fn run_predicate_verify(args: TimestampPredicateVerifyArgs) -> Result<()> {
    let params = read_params(BufReader::new(File::open(&args.params)?))?;
    let proof: TimestampPredicateProof = decode_proof_file(&args.proof)?;
    if proof.public_inputs.len() != TIMESTAMP_PREDICATE_PUBLIC_INPUTS {
        anyhow::bail!("wrong predicate public input arity");
    }
    let vk = timestamp_predicate_verifying_key_for(&params)?;
    verify_timestamp_predicate(&params, &vk, &proof.public_inputs, &proof.proof)?;
    if let Some(path) = &args.receipt {
        let receipt = load_receipt(path)?;
        assert_predicate_receipt_matches(&receipt, &proof)?;
    }
    print_predicate_public_inputs(&proof);
    println!("OK: predicate proof verified");
    Ok(())
}

fn hash_file_for_timestamp(path: &PathBuf) -> Result<(u128, u128, [u8; 32])> {
    let mut file =
        File::open(path).with_context(|| format!("failed to open {}", path.display()))?;
    let mut hasher = Sha256::new();
    std::io::copy(&mut file, &mut hasher)?;
    let digest = hasher.finalize();
    let mut full = [0u8; 32];
    full.copy_from_slice(&digest[..32]);
    let lo = u128::from_le_bytes(full[..16].try_into().expect("16 bytes"));
    let hi = u128::from_le_bytes(full[16..32].try_into().expect("16 bytes"));
    Ok((lo, hi, full))
}

fn load_receipt(path: &PathBuf) -> Result<TimestampReceipt> {
    Ok(serde_json::from_reader(BufReader::new(File::open(path)?))?)
}

fn decode_proof_file<T>(path: &PathBuf) -> Result<T>
where
    T: serde::de::DeserializeOwned,
{
    let metadata =
        std::fs::metadata(path).with_context(|| format!("failed to stat {}", path.display()))?;
    if metadata.len() > MAX_PROOF_BYTES {
        anyhow::bail!(
            "proof file {} is too large: {} bytes > {}",
            path.display(),
            metadata.len(),
            MAX_PROOF_BYTES
        );
    }
    let mut reader = BufReader::new(File::open(path)?);
    let decoded = serde_json::from_reader(&mut reader)?;
    Ok(decoded)
}

fn assert_receipt_matches_open_proof(path: &PathBuf, proof: &TimestampProof) -> Result<()> {
    let receipt = load_receipt(path)?;
    let commitment = hex_le(&proof.public_inputs[0]);
    if commitment != receipt.commitment {
        anyhow::bail!("receipt commitment does not match proof commitment");
    }
    let block_height = field_repr_to_u64(&proof.public_inputs[1])?;
    if block_height != receipt.block_height {
        anyhow::bail!("receipt block_height does not match proof block_height");
    }
    Ok(())
}

fn assert_predicate_receipt_matches(
    receipt: &TimestampReceipt,
    proof: &TimestampPredicateProof,
) -> Result<()> {
    let commitment = hex_le(&proof.public_inputs[0]);
    if receipt.commitment != commitment {
        anyhow::bail!("receipt commitment does not match predicate proof");
    }
    let block_height = field_repr_to_u64(&proof.public_inputs[1])?;
    if receipt.block_height != block_height {
        anyhow::bail!("receipt block_height does not match predicate proof block_height");
    }
    Ok(())
}

fn build_rpc(
    network: Network,
    url: Url,
    from_address: String,
    rpc_user: Option<String>,
    rpc_password: Option<String>,
) -> Result<ZalletRpc> {
    let mut config = ZalletConfig::for_network(network, url, from_address);
    if let (Some(user), Some(password)) = (rpc_user, rpc_password) {
        config = config.with_auth(ZalletAuth { user, password });
    }
    if let Ok(path) = std::env::var("ZECTIME_WALLET_DB_PATH") {
        if !path.is_empty() {
            config = config.with_wallet_db_path(path);
        }
    }
    ZalletRpc::new(config).context("failed to construct zallet RPC client")
}

fn parse_network(s: &str) -> Result<Network, String> {
    s.parse::<Network>().map_err(|e| e.to_string())
}

fn parse_txid(s: &str) -> Result<TxId> {
    let bytes = hex::decode(s).with_context(|| format!("invalid txid hex `{s}`"))?;
    let len = bytes.len();
    bytes
        .try_into()
        .map_err(|_| anyhow!("txid decoded to {len} bytes; expected 32"))
}

fn parse_hex_le_commitment(hex_str: &str) -> Result<[u8; 32]> {
    let trimmed = hex_str.strip_prefix("0x").unwrap_or(hex_str);
    let decoded = hex::decode(trimmed)?;
    if decoded.len() != 32 {
        anyhow::bail!("commitment must decode to 32 bytes");
    }
    let mut le = [0u8; 32];
    for (i, b) in decoded.iter().enumerate() {
        le[31 - i] = *b;
    }
    Ok(le)
}

fn parse_u128_hex(value: &str, field: &str) -> Result<u128> {
    let trimmed = value.strip_prefix("0x").unwrap_or(value);
    u128::from_str_radix(trimmed, 16)
        .with_context(|| format!("field `{field}` is not valid hex u128"))
}

fn field_repr_to_u64(bytes: &[u8; 32]) -> Result<u64> {
    for (i, b) in bytes.iter().enumerate().skip(8) {
        if *b != 0 {
            return Err(anyhow!("value does not fit in u64; non-zero byte at {i}"));
        }
    }
    Ok(u64::from_le_bytes(bytes[..8].try_into().expect("8 bytes")))
}

fn print_timestamp_public_inputs(proof: &TimestampProof) {
    for (i, bytes) in proof.public_inputs.iter().enumerate() {
        let label = match i {
            0 => "commitment",
            1 => "block_height",
            _ => "unknown",
        };
        println!("  [{i}] {label} = 0x{}", hex_le(bytes));
    }
}

fn print_predicate_public_inputs(proof: &TimestampPredicateProof) {
    for (i, bytes) in proof.public_inputs.iter().enumerate() {
        let label = match i {
            0 => "commitment",
            1 => "block_height",
            2 => "claim_hash",
            _ => "unknown",
        };
        println!("  [{i}] {label} = 0x{}", hex_le(bytes));
    }
}

fn hex_le(bytes: &[u8; 32]) -> String {
    let mut s = String::with_capacity(64);
    for b in bytes.iter().rev() {
        let _ = write!(&mut s, "{b:02x}");
    }
    s
}

fn create_file(path: &PathBuf) -> Result<File> {
    OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(path)
        .with_context(|| format!("failed to create {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn proof_with_height(commitment: [u8; 32], block_height: u64) -> TimestampPredicateProof {
        let mut height = [0u8; 32];
        height[..8].copy_from_slice(&block_height.to_le_bytes());
        TimestampPredicateProof {
            public_inputs: vec![commitment, height, [0x66; 32]],
            proof: Vec::new(),
        }
    }

    fn receipt_for(commitment: [u8; 32], block_height: u64) -> TimestampReceipt {
        TimestampReceipt {
            commitment_scheme: default_commitment_scheme(),
            commitment: hex_le(&commitment),
            block_height,
            nonce: "22".repeat(16),
            doc_hash_lo: "33".repeat(16),
            doc_hash_hi: "44".repeat(16),
            doc_hash_sha256: "55".repeat(32),
        }
    }

    #[test]
    fn predicate_receipt_match_requires_block_height() {
        let commitment = [0x11; 32];
        let receipt = receipt_for(commitment, 100);
        let proof = proof_with_height(commitment, 100);

        assert!(assert_predicate_receipt_matches(&receipt, &proof).is_ok());

        let wrong_height = proof_with_height(commitment, 101);
        let err = assert_predicate_receipt_matches(&receipt, &wrong_height).unwrap_err();
        assert!(
            err.to_string().contains("block_height"),
            "unexpected error: {err}"
        );
    }
}
